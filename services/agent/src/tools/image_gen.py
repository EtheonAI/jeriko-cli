"""
Image generation via Nano Banana (Gemini API).

Generates images by running google-generativeai inside the E2B sandbox.
The Gemini model generates high-quality images with accurate text rendering
at ~$0.05/image. Images are saved to the sandbox filesystem.
"""

import textwrap

import structlog

from ..config import settings
from .browser import _sandbox_code_execute

logger = structlog.get_logger()


async def nano_banana_generate(
    sandbox_id: str | None,
    prompt: str,
    filename: str = "generated_image.png",
) -> dict:
    """
    Generate an image using Nano Banana (Gemini) API.

    The script runs inside the E2B sandbox where google-generativeai is pre-installed.
    The image is saved to /home/user/output/{filename}.
    """
    if not sandbox_id:
        return await _direct_gemini_generate(prompt, filename)

    safe_prompt = prompt.replace("\\", "\\\\").replace('"', '\\"').replace("'", "\\'")
    safe_filename = filename.replace("\\", "\\\\").replace('"', '\\"')

    script = textwrap.dedent(f"""\
        import json
        import os

        try:
            from google import genai

            client = genai.Client()

            response = client.models.generate_content(
                model="gemini-2.0-flash-exp",
                contents=["{safe_prompt}"],
                config=genai.types.GenerateContentConfig(
                    response_modalities=["IMAGE", "TEXT"],
                ),
            )

            # Save image to sandbox filesystem
            os.makedirs("/home/user/output", exist_ok=True)
            output_path = f"/home/user/output/{safe_filename}"

            for part in response.candidates[0].content.parts:
                if hasattr(part, "inline_data") and part.inline_data:
                    with open(output_path, "wb") as f:
                        f.write(part.inline_data.data)
                    print(json.dumps({{
                        "image_path": output_path,
                        "prompt": "{safe_prompt}",
                        "model": "nano-banana",
                        "filename": "{safe_filename}",
                        "generated": True,
                    }}))
                    break
            else:
                # No image data in response
                text_parts = [
                    p.text for p in response.candidates[0].content.parts
                    if hasattr(p, "text") and p.text
                ]
                print(json.dumps({{
                    "error": "No image generated",
                    "text_response": " ".join(text_parts) if text_parts else "Empty response",
                    "prompt": "{safe_prompt}",
                }}))

        except Exception as e:
            print(json.dumps({{"error": str(e), "prompt": "{safe_prompt}"}}))
    """)

    return await _sandbox_code_execute(sandbox_id, script, timeout=60)


async def _direct_gemini_generate(prompt: str, filename: str) -> dict:
    """
    Fallback: generate image directly from the agent service using Gemini API.
    Only used when no sandbox is available.
    """
    if not settings.google_api_key:
        return {
            "error": "Image generation not configured. GOOGLE_API_KEY is missing.",
            "prompt": prompt,
        }

    try:
        from google import genai

        client = genai.Client(api_key=settings.google_api_key)

        response = client.models.generate_content(
            model="gemini-2.0-flash-exp",
            contents=[prompt],
            config=genai.types.GenerateContentConfig(
                response_modalities=["IMAGE", "TEXT"],
            ),
        )

        for part in response.candidates[0].content.parts:
            if hasattr(part, "inline_data") and part.inline_data:
                import base64

                image_b64 = base64.b64encode(part.inline_data.data).decode()
                return {
                    "image_data": image_b64,
                    "prompt": prompt,
                    "model": "nano-banana",
                    "filename": filename,
                    "generated": True,
                    "note": "Image generated without sandbox. Base64 data included.",
                }

        return {"error": "No image generated by Gemini", "prompt": prompt}

    except ImportError:
        return {
            "error": "google-generativeai package not installed",
            "prompt": prompt,
        }
    except Exception as e:
        return {"error": f"Image generation failed: {str(e)}", "prompt": prompt}
